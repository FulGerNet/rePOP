"""Build the HD menu font a target's renderer substitutes for its font sheet.

    python tools/hd-font.py xbox-demo
    python tools/hd-font.py xbox-retail

Input, in the ignored Assets/fonts/<target>/: font_0B0041BB.png, the title's
512x128 sheet (texture 0x0B0041BB, FONTDESC 0x0B0041BC) exported upright, and
font_<demo|retail>_hd.png, the user's HD drawing of it. The HD drawing has its
own margins and line spacing, so it is mapped onto the sheet's grid by one
linear map per axis that takes the bounding box of its glyphs onto the
sheet's, then resampled to 2048x512. Output: port/game/resot_hd_font_<target>.h,
the coverage (alpha) only in 16 levels, white glyphs, run-length coded,
upright. The sheet's pixels themselves are not written anywhere.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
W, H = 2048, 512

try:
    from PIL import Image
except ImportError:
    sys.path.insert(0, str(ROOT.parent / "pop-bf-lab" / "vendor"))
    from PIL import Image


def glyph_box(img):
    return img.getchannel("A").point(lambda a: 255 if a > 64 else 0).getbbox()


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "xbox-demo"
    short = target.split("-")[1]
    folder = ROOT / "Assets" / "fonts" / target
    sheet = Image.open(folder / "font_0B0041BB.png").convert("RGBA")
    hd = Image.open(folder / f"font_{short}_hd.png").convert("RGBA")
    sb, hb = glyph_box(sheet), glyph_box(hd)
    sw, sh = sheet.size
    # Sheet fraction f maps to HD pixel a*f + b on each axis.
    ax = (hb[2] - hb[0]) / ((sb[2] - sb[0]) / sw)
    bx = hb[0] - ax * sb[0] / sw
    ay = (hb[3] - hb[1]) / ((sb[3] - sb[1]) / sh)
    by = hb[1] - ay * sb[1] / sh
    box = (bx, by, bx + ax, by + ay)
    alpha = hd.getchannel("A").transform((W, H), Image.Transform.EXTENT, box,
                                         Image.Resampling.BICUBIC)
    # Check: the mapped glyphs against the sheet's, at the sheet's size.
    small = alpha.resize((sw, sh), Image.Resampling.BOX).point(lambda a: 1 if a > 64 else 0)
    ref = sheet.getchannel("A").point(lambda a: 1 if a > 64 else 0)
    pairs = list(zip(small.tobytes(), ref.tobytes()))
    both = sum(1 for p, q in pairs if p and q)
    either = sum(1 for p, q in pairs if p or q)
    print(f"{target}: HD box {hb}, sheet box {sb}, overlap {both / either:.3f}")
    data = bytes(b >> 4 for b in alpha.tobytes())     # 16 coverage levels
    runs = bytearray()
    i = 0
    while i < len(data):
        v, n = data[i], 1
        while i + n < len(data) and data[i + n] == v and n < 16:
            n += 1
        runs.append(v << 4 | (n - 1))
        i += n
    out = ROOT / "port" / "game" / f"resot_hd_font_{target.replace('-', '_')}.h"
    lines = [f"/* Generated by tools/hd-font.py {target} from the user's HD menu font:",
             f" * {W}x{H} coverage in 16 levels, upright; each byte level << 4 | run - 1.",
             " * Do not edit. */",
             f"#define RESOT_HD_FONT_W {W}u", f"#define RESOT_HD_FONT_H {H}u",
             f"static const unsigned char s_resot_hd_font_rle[{len(runs)}] = {{"]
    for j in range(0, len(runs), 24):
        lines.append("    " + ",".join(str(b) for b in runs[j:j + 24]) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(runs)} bytes of runs")


if __name__ == "__main__":
    main()
