"""Make a target's HD menu logo header from the user's own image.

    python tools/hd-logo.py xbox-retail|xbox-demo [image]

Input: the image given, else the ignored Assets/ui/logomenu-<target>.png (copied
there when given). It is fitted to 1024x256, four times the title's 256x64 logo
texture, on premultiplied colour; colour is extended under transparent pixels
so the filter leaves no fringe.

Output: port/game/resot_hd_logo_<target>.h, ignored like the image: it holds
the user's artwork, so a checkout without it builds and draws the game's logo.
Runs of (count, 0xAARRGGBB), upright. The runtime is resot_hd_logo.h.
"""
import shutil
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
W, H = 1024, 256


def main():
    target = sys.argv[1]
    if target not in ("xbox-retail", "xbox-demo"):
        sys.exit(__doc__)
    store = ROOT / "Assets" / "ui" / f"logomenu-{target}.png"
    if len(sys.argv) > 2:
        store.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(sys.argv[2], store)
    im = Image.open(store).convert("RGBA")
    a = np.asarray(im, np.float64) / 255.0
    channels = [a[..., c] * a[..., 3] for c in range(3)] + [a[..., 3]]
    resized = [np.asarray(Image.fromarray(c.astype(np.float32), "F").resize((W, H), Image.LANCZOS))
               for c in channels]
    alpha = np.clip(resized[3], 0.0, 1.0)
    rgb = np.stack([np.clip(c / np.maximum(alpha, 1e-3), 0.0, 1.0) for c in resized[:3]], -1)
    _, (iy, ix) = ndimage.distance_transform_edt(alpha < 1 / 255, return_indices=True)
    rgb = rgb[iy, ix]
    q = np.rint(rgb * 255).astype(np.uint32)
    words = np.rint(alpha * 255).astype(np.uint32) << 24 | q[..., 0] << 16 | q[..., 1] << 8 | q[..., 2]
    flat = words.ravel().tolist()
    runs = []
    i = 0
    while i < len(flat):
        n = 1
        while i + n < len(flat) and flat[i + n] == flat[i]:
            n += 1
        runs += [n, flat[i]]
        i += n
    dst = ROOT / "port" / "game" / f"resot_hd_logo_{target.replace('-', '_')}.h"
    lines = ["/* Generated by tools/hd-logo.py from the user's image. Ignored: do not",
             " * publish. Upright, pairs (run, 0xAARRGGBB). Do not edit. */",
             f"#define RESOT_HD_LOGO_DATA_W {W}u",
             f"#define RESOT_HD_LOGO_DATA_H {H}u",
             f"static const unsigned int s_resot_hd_logo_rle[{len(runs)}] = {{"]
    for j in range(0, len(runs), 12):
        lines.append("    " + ",".join(f"{v}u" for v in runs[j:j + 12]) + ",")
    lines.append("};")
    dst.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{im.size[0]}x{im.size[1]} -> {W}x{H}, {len(runs) // 2} runs, {dst.stat().st_size} bytes: {dst.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
