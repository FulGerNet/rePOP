"""Host GLSL helpers derived from reSOT's reference HLSL; no game programs."""
import re
import json


def header(check, text):
    common = check.embedded(text, "s_hw_hlsl_vs_common")
    finish = common[common.index("VO vs_finish"):]
    finish = finish.replace("VO vs_finish", "void vs_finish").replace("VO o;", "")
    finish = finish.replace("return o;", "return;")
    finish = finish.replace("o.pos", "gl_Position")
    for name in ("d0", "d1", "fog", "t0", "t1", "t2", "t3"):
        finish = finish.replace(f"o.{name}", f"out_{name}")
    head = check.embedded(text, "s_hw_hlsl_vsp_head")
    helpers = head[head.index("static const float VSH_INF"):head.index("VO vs_prog")]
    helpers = helpers.replace("static const float VSH_INF = asfloat(0x7F800000);",
                              "#define VSH_INF uintBitsToFloat(0x7F800000u)")
    helpers = helpers.replace("(uint)fogp.z", "uint(fogp.z)")
    glsl = "#version 450\n"
    glsl += "layout(std140,set=1,binding=0) uniform Header { vec4 vp, fogp, ws, vpad; };\n"
    glsl += "layout(std140,set=1,binding=1) uniform Constants { vec4 c[192]; };\n"
    glsl += "float saturate(float x) { return clamp(x,0.0,1.0); }\n"
    glsl += "vec4 saturate(vec4 x) { return clamp(x,0.0,1.0); }\n"
    for slot in range(8):
        glsl += f"layout(location={slot}) in vec4 vin{slot};\n"
    for slot, name in enumerate(("d0", "d1", "fog", "t0", "t1", "t2", "t3")):
        glsl += f"layout(location={slot}) out vec4 out_{name};\n"
    finish = re.sub(r"\bflat\b", "is_flat", finish)  # GLSL interpolation keyword.
    glsl += helpers + finish
    glsl = re.sub(r"\bfloat4\b", "vec4", glsl)
    return '/* RE-SoT: shared shader math; generated by native-vertex-source.py. */\n' + \
           'static const char ng_translated_vertex_head[] =\n' + \
           '\n'.join(json.dumps(line + '\n') for line in glsl.splitlines()) + ';\n'
